function styleText(text: string, rules: readonly (readonly [RegExp, string])[]): string {
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const saved: string[] = [];
  let body = text.trim();
  for (const pattern of PROTECTED) {
    body = body.replace(pattern, (part) => {
      const marker = "\uE000" + saved.length + "\uE001";
      saved.push(part);
      return marker;
    });
  }
  for (const [pattern, replacement] of rules) body = body.replace(pattern, replacement);
  body = body.replace(/\uE000(\d+)\uE001/g, (_, index: string) => saved[Number(index)] ?? "");
  return leading + body + trailing;
}

